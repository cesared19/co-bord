import { CheckCircle2, ExternalLink } from 'lucide-react'
import { useMemo, useState } from 'react'
import { Button, ErrorText, Modal } from '../components/ui'
import { api } from '../lib/api'
import { flowPaths, sectionPart } from './flow'
import type { ElementMap } from './geometry'
import { canWriteSparky, type SparkyInfo, sparkyHref } from './sparky'
import type { BoardStore } from './store'
import type { SparkyLink } from './types'

interface GenerateResult {
	section: { id: string; path: string; webPath: string }
	cases: { sourceRef: string; testCaseNumber: number; title: string; created: boolean; webPath: string }[]
	plan: { id: string; name: string; created: boolean; webPath: string } | null
}

/**
 * Creates one SparkyTC test case per path through a flow (the board or a frame), with a step for each move
 * (action: the step, expected: the next one), and a test plan with them. The steps are linked to the test cases
 * that go through them. Generating again reuses the test cases already created.
 */
export function GenerateTestsDialog({
	boardId,
	boardName,
	elements,
	store,
	info,
	initialFrameId,
	onClose,
}: {
	boardId: string
	boardName: string
	elements: ElementMap
	store: BoardStore
	info: SparkyInfo
	initialFrameId: string | null
	onClose: () => void
}) {
	const frames = useMemo(
		() => [...elements.values()].filter((el) => el.type === 'frame').sort((a, b) => a.y - b.y || a.x - b.x),
		[elements],
	)
	const [scope, setScope] = useState(initialFrameId ?? '')
	const frame = frames.find((f) => f.id === scope)
	const scopeName = frame?.type === 'frame' ? frame.title || 'Frame' : boardName
	const defaultSection = ['co-bord', sectionPart(boardName), ...(frame ? [sectionPart(scopeName)] : [])].join(' / ')
	const [section, setSection] = useState<string | null>(null)
	const [withPlan, setWithPlan] = useState(true)
	const [planName, setPlanName] = useState<string | null>(null)
	const [link, setLink] = useState(true)
	const [busy, setBusy] = useState(false)
	const [error, setError] = useState('')
	const [done, setDone] = useState<GenerateResult | null>(null)

	const { paths, truncated, unconnected } = useMemo(
		() => flowPaths(elements, frame?.id ?? null, { boardId, scopeName }),
		[elements, frame?.id, boardId, scopeName],
	)
	const canWrite = canWriteSparky(info)
	const sectionPath = (section ?? defaultSection).trim()
	const plan = (planName ?? `${boardName}${frame ? ` – ${scopeName}` : ''}: flow paths`).trim()

	async function generate() {
		setBusy(true)
		setError('')
		try {
			const result = await api<GenerateResult>(`/api/boards/${boardId}/sparkytc/generate`, {
				method: 'POST',
				body: {
					sectionPath,
					...(withPlan ? { planName: plan, planSourceRef: `cobord:${boardId}:plan:${frame?.id ?? 'board'}` } : {}),
					cases: paths.map((p) => ({
						title: p.title,
						description: `Generated by co-bord from a path through ${scopeName}.\n${window.location.origin}/boards/${boardId}`,
						sourceRef: p.sourceRef,
						steps: p.steps,
					})),
				},
			})
			if (link) {
				// each step gets the test cases that go through it, and the frame the plan
				const byRef = new Map(result.cases.map((c) => [c.sourceRef, c]))
				const add = new Map<string, SparkyLink[]>()
				for (const p of paths) {
					const c = byRef.get(p.sourceRef)
					if (!c) continue
					for (const id of p.nodes)
						add.set(id, [...(add.get(id) ?? []), { kind: 'case', id: String(c.testCaseNumber), label: `#${c.testCaseNumber} ${c.title}` }])
				}
				if (frame && result.plan) add.set(frame.id, [{ kind: 'plan', id: result.plan.id, label: result.plan.name }])
				const updates: [string, { links: SparkyLink[] }][] = []
				for (const [id, links] of add) {
					const el = store.get(id)
					if (!el || el.type === 'connector') continue
					const current = el.links ?? []
					const missing = links.filter(
						(l, i) => !current.some((c) => c.kind === l.kind && c.id === l.id) && links.findIndex((x) => x.id === l.id) === i,
					)
					if (missing.length) updates.push([id, { links: [...current, ...missing] }])
				}
				if (updates.length) {
					store.checkpoint()
					store.update(updates)
					store.checkpoint()
				}
			}
			setDone(result)
		} catch (e) {
			setError((e as Error).message)
		} finally {
			setBusy(false)
		}
	}

	const input = 'w-full rounded-md border border-gray-300 bg-white px-3 py-2 text-sm dark:border-gray-700 dark:bg-gray-900'
	if (done) {
		const created = done.cases.filter((c) => c.created).length
		const sectionUrl = sparkyHref(info, done.section.webPath)
		const planUrl = done.plan ? sparkyHref(info, done.plan.webPath) : undefined
		return (
			<Modal title="Generate tests" onClose={onClose}>
				<div className="space-y-4 text-sm">
					<p className="flex items-start gap-2">
						<CheckCircle2 size={18} className="mt-0.5 shrink-0 text-green-600" />
						<span>
							{created} new test {created === 1 ? 'case' : 'cases'}
							{done.cases.length > created ? `, ${done.cases.length - created} already there` : ''} in {done.section.path}
							{done.plan ? `, ${done.plan.created ? 'and the test plan' : 'in the test plan'} ${done.plan.name}` : ''}.
						</span>
					</p>
					<div className="flex flex-wrap gap-2">
						{planUrl && (
							<a
								href={planUrl}
								target="_blank"
								rel="noopener noreferrer"
								className="inline-flex items-center gap-2 rounded-md bg-brand-600 px-3 py-2 font-medium text-white hover:bg-brand-700"
							>
								<ExternalLink size={16} /> Open the plan
							</a>
						)}
						{sectionUrl && (
							<a
								href={sectionUrl}
								target="_blank"
								rel="noopener noreferrer"
								className="inline-flex items-center gap-2 rounded-md border border-gray-300 px-3 py-2 font-medium hover:bg-gray-50 dark:border-gray-600 dark:hover:bg-gray-800"
							>
								<ExternalLink size={16} /> Open the section
							</a>
						)}
						<Button variant="secondary" onClick={onClose}>
							Close
						</Button>
					</div>
				</div>
			</Modal>
		)
	}

	return (
		<Modal title="Generate tests" onClose={onClose}>
			<form
				className="space-y-4 text-sm"
				onSubmit={(e) => {
					e.preventDefault()
					void generate()
				}}
			>
				<p className="text-gray-600 dark:text-gray-400">
					One test case for each way through the flow, following the connectors from where it starts to where it ends. Each step is an
					action, and the next step is what should happen.
				</p>
				<label className="block">
					<span className="mb-1 block font-medium">Flow</span>
					<select value={scope} onChange={(e) => setScope(e.target.value)} className={input}>
						<option value="">The whole board</option>
						{frames.map((f) => (
							<option key={f.id} value={f.id}>
								Frame: {f.type === 'frame' ? f.title || 'Frame' : ''}
							</option>
						))}
					</select>
				</label>

				<div>
					<p className="mb-1 font-medium">
						{paths.length} {paths.length === 1 ? 'path' : 'paths'}
						{truncated ? ' (only the first 100)' : ''}
					</p>
					{paths.length === 0 ? (
						<p className="rounded-md bg-gray-50 px-3 py-2 text-gray-600 dark:bg-gray-800 dark:text-gray-300">
							Connect shapes or sticky notes with connectors to make a flow.
						</p>
					) : (
						<ol className="max-h-48 space-y-1 overflow-auto rounded-md border border-gray-200 p-2 dark:border-gray-700" aria-label="Paths">
							{paths.map((p) => (
								<li key={p.sourceRef} className="text-xs">
									<span className="block truncate font-medium" title={p.title}>
										{p.title}
									</span>
									<span className="text-gray-500">
										{p.steps.length} {p.steps.length === 1 ? 'step' : 'steps'}
									</span>
								</li>
							))}
						</ol>
					)}
					{unconnected > 0 && (
						<p className="mt-1 text-xs text-gray-500">
							{unconnected} {unconnected === 1 ? 'step is' : 'steps are'} not connected to the flow and left out.
						</p>
					)}
				</div>

				<label className="block">
					<span className="mb-1 block font-medium">Section in SparkyTC</span>
					<input
						value={section ?? defaultSection}
						onChange={(e) => setSection(e.target.value)}
						required
						maxLength={500}
						className={input}
					/>
					<span className="mt-1 block text-xs text-gray-500">Suites and sections separated by " / "; missing ones are created.</span>
				</label>
				<label className="flex items-start gap-2">
					<input type="checkbox" checked={withPlan} onChange={(e) => setWithPlan(e.target.checked)} className="mt-0.5 accent-brand-600" />
					<span>Create a test plan with the section</span>
				</label>
				{withPlan && (
					<input
						aria-label="Test plan name"
						value={planName ?? plan}
						onChange={(e) => setPlanName(e.target.value)}
						required
						maxLength={200}
						className={input}
					/>
				)}
				<label className="flex items-start gap-2">
					<input type="checkbox" checked={link} onChange={(e) => setLink(e.target.checked)} className="mt-0.5 accent-brand-600" />
					<span>
						Link each step to the test cases that go through it
						<span className="block text-xs text-gray-500">So coverage and results show on the flow.</span>
					</span>
				</label>
				{!canWrite && (
					<p className="rounded-md bg-amber-50 px-3 py-2 text-amber-800 dark:bg-amber-950/50 dark:text-amber-200">
						The SparkyTC token of this project can only read. An admin can connect a Read and write token (SparkyTC 2.3.0 or later) in the
						project settings.
					</p>
				)}
				<p className="text-xs text-gray-500">Generating again adds only the new paths; the test cases already created are reused.</p>
				<ErrorText>{error}</ErrorText>
				<div className="flex justify-end gap-2">
					<Button variant="secondary" onClick={onClose}>
						Cancel
					</Button>
					<Button type="submit" disabled={busy || !canWrite || !paths.length || !sectionPath || (withPlan && !plan)}>
						{busy ? 'Creating…' : `Create ${paths.length} test ${paths.length === 1 ? 'case' : 'cases'}`}
					</Button>
				</div>
			</form>
		</Modal>
	)
}
